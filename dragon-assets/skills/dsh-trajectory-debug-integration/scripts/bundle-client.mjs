#!/usr/bin/env node
/**
 * Build the browser client bundle for dsh-client-ui-trajectory-debug.
 *
 * DSH's browser module system loads client plugins as
 * `window.__ModuleLoader__.load({ id, factory: (require) => … })` CommonJS
 * factories; the shell provides `react` / `react-dom` as seed modules. This
 * script bundles our client entry with esbuild into exactly that format:
 *
 * - entry: packages/client-ui-trajectory-debug/src/client/index.ts
 * - format: cjs (the factory's `require` parameter binds the bare calls)
 * - externals: react (+ react-dom / react/jsx-runtime for future JSX use);
 *   every other import in our client is type-only or local, so nothing else
 *   needs the module table.
 * - output: packages/client-ui-trajectory-debug/lib/client.js
 *   (overwrites the tsc-emitted ESM placeholder; run AFTER `pnpm -r build`).
 *
 * Usage: node scripts/bundle-client.mjs
 */

import { buildSync } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PKG = join(ROOT, 'packages', 'client-ui-trajectory-debug')
const ENTRY = join(PKG, 'src', 'client', 'index.ts')
const OUT = join(PKG, 'lib', 'client.js')
const ID = 'dsh-client-ui-trajectory-debug'

if (!readFileSync(ENTRY, 'utf8').includes('export function apply')) {
  throw new Error(`unexpected client entry: ${ENTRY}`)
}

const result = buildSync({
  entryPoints: [ENTRY],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  write: false,
  sourcemap: false,
  minify: true,
  logLevel: 'warning',
})

const body = result.outputFiles[0].text
const wrapped = [
  '/* Trajectory Debug Workbench — browser bundle (generated by scripts/bundle-client.mjs) */',
  'window.__ModuleLoader__.load({',
  `\tid: ${JSON.stringify(ID)},`,
  '\tfactory: (require) => {',
  '\t\tvar module = { exports: {} };',
  '\t\tvar exports = module.exports;',
  '\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
  body,
  '\t\treturn module.exports;',
  '\t},',
  '});',
  '',
].join('\n')

writeFileSync(OUT, wrapped)
console.log(`[bundle-client] wrote ${OUT} (${wrapped.length} chars, minified)`)

// Sanity: the bundle must register the exact graph id and require react.
if (!wrapped.includes(`id: "${ID}"`)) throw new Error('bundle missing graph id')
if (!/require\("react"\)/.test(wrapped)) {
  console.warn('[bundle-client] warning: no require("react") found — check externals')
}
console.log('[bundle-client] OK')
